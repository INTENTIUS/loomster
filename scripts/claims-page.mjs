// Writes the "Recorded claims" table of docs-site reference/validation from
// the recorded claim runs (test/claims-record.json, which `just claims`
// appends to) and the claims catalog (the headers of test/claims/*/*.sh), so
// the page states only what a recorded run showed (#55). It also sets the
// page's `claims:` front matter to the claims with a recorded run.
//
//   node scripts/claims-page.mjs           (npm run claims:page) rewrite the page
//   node scripts/claims-page.mjs --check   exit 1 when the page is stale
//
// scripts/lint-docs.mjs runs the same check.
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

export const RECORD = "test/claims-record.json";
export const PAGE = "docs-site/src/content/docs/reference/validation.md";
const START = "<!-- claims:start (generated by scripts/claims-page.mjs from test/claims-record.json; do not edit) -->";
const END = "<!-- claims:end -->";

const walk = (p) => (statSync(p).isDirectory() ? readdirSync(p).sort().flatMap((e) => walk(join(p, e))) : [p]);

/** name -> { target, summary } from each claim script's header. */
export function catalog(dir = "test/claims") {
  const out = new Map();
  for (const f of walk(dir).filter((f) => f.endsWith(".sh"))) {
    const name = f.slice(dir.length + 1, -3);
    const head = readFileSync(f, "utf8").split("\n").slice(0, 40);
    const field = (k) => head.find((l) => l.startsWith(`# ${k}:`))?.slice(k.length + 3).trim() ?? "";
    out.set(name, { target: field("target"), summary: field("summary") });
  }
  return out;
}

const cell = (s) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const clip = (s, n = 280) => (s.length > n ? `${s.slice(0, n - 3).trimEnd()}...` : s);

/** The page text with the table and the front matter written from the record. */
export function render(pageText, rows, claims) {
  const byClaim = new Map();
  for (const r of rows) {
    if (!byClaim.has(r.claim)) byClaim.set(r.claim, {});
    byClaim.get(r.claim)[r.run] = r;
  }
  const run = (r) => (r ? cell(clip(`${r.verdict}${r.detail ? `: ${r.detail}` : ""}`)) : "no recorded run");
  const when = (p, b) => {
    const r = [p, b].filter(Boolean).sort((x, y) => (x.timestamp < y.timestamp ? 1 : -1))[0];
    return r ? `${r.timestamp.slice(0, 10)}, ${r.sha}` : "";
  };
  const lines = [
    START,
    "| Claim | Target | Plain | BREAK | Recorded |",
    "|---|---|---|---|---|",
    ...[...claims.keys()].sort().map((name) => {
      const { plain, break: brk } = byClaim.get(name) ?? {};
      return `| \`${name}\` | ${claims.get(name).target} | ${run(plain)} | ${run(brk)} | ${when(plain, brk)} |`;
    }),
    END,
  ];
  const s = pageText.indexOf(START.slice(0, 20));
  const e = pageText.indexOf(END);
  if (s === -1 || e === -1) throw new Error(`${PAGE} has no ${START.slice(0, 20)} ... ${END} block`);
  let text = pageText.slice(0, s) + lines.join("\n") + pageText.slice(e + END.length);
  const recorded = [...byClaim.keys()].filter((c) => claims.has(c)).sort();
  text = text.replace(/^claims: \[[^\]]*\]$/m, `claims: [${recorded.join(", ")}]`);
  return text;
}

export function readRecord(path = RECORD) {
  return existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : [];
}

/** null when the page matches the record, else the text it should have. */
export function stale() {
  const text = readFileSync(PAGE, "utf8");
  const want = render(text, readRecord(), catalog());
  return want === text ? null : want;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = stale();
  if (process.argv.includes("--check")) {
    if (want) { console.log(`claims-page: ${PAGE} is stale; run npm run claims:page`); process.exit(1); }
    console.log("claims-page: up to date");
  } else if (want) {
    writeFileSync(PAGE, want);
    console.log(`claims-page: wrote ${PAGE}`);
  } else {
    console.log("claims-page: up to date");
  }
}
